package praktikum2;


public class OperasiMatematika {
    public static void main(String[] args) {
        double x = 22;
        double y = 33;
        
        System.out.println("Penjumlahan :" + (x + y));
        System.out.println("Pengurangan :" + (x - y));
        System.out.println("Perkalian :" + (x * y));
        System.out.println("Pembagian :" + (x / y));
    }
}
